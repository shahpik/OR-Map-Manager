"""
    multi_replace(string::AbstractString, multipair_replace::AbstractVector{Pair{String, String}})

Recursively apply the replace function to the string, applying the pairs from first to last in the provided vector.
"""
multi_replace(string::AbstractString, multipair_replace::AbstractVector) = _multi_replace(string, multipair_replace, length(multipair_replace))


"""
    _multi_replace(string::AbstractString, multipair_replace::AbstractVector, multipair_length::Int)

Recursively apply the replace function to the string, applying the pairs from first to last in the provided vector, based on an indexing length.
This is used by `multi_replace`, and should not be accessed directly otherwise.
"""
function _multi_replace(string::AbstractString, multipair_replace::AbstractVector, multipair_length::Int)
    if multipair_length == 0
        return string
    end
    apply_index = length(multipair_replace) - multipair_length + 1
    return _multi_replace(replace(string, multipair_replace[apply_index]), multipair_replace, multipair_length-1)
end


"""
    dollar_marked_values(array_like)

Creates a joined string of the values in array_like, with a \$ preceding each value.

```
dollar_marked_values([1, 2, 3])
>>> "(\$1, \$2, \$3)"
```
"""
dollar_marked_values(array_like) = "(\$" * join(array_like, ", \$") * ")"


