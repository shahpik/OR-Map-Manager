"""
    get_unique_name(name::U, taken_names::AbstractVector{U}) where U<:AbstractString

Checks that the name is unique in the provided list of names. If it's not, a new name
is generated by appending a number up to 10,000. If this threshold is reached, then a
uuid4 unique string is appended instead.
"""
function get_unique_name(name::U, taken_names::AbstractVector{U}) where U<:AbstractString
    if name ∉ taken_names
        return name
    end
    i = 1
    while i < 10000
        new_name = "$(name)_$(i)"
        if new_name ∉ taken_names
            return new_name
        end
    end
    uuid = uuid4().value
    return "$(name)_$(uuid)"
end

"""
    snake_to_camel(str::AbstractString)

Converts snake case to camel case.
"""
function snake_to_camel(str::AbstractString)
    camel_str = join(uppercasefirst.(split(str, "_")))
    return lowercase(camel_str[1]) * camel_str[2:end]
end

