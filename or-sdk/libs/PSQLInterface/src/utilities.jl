"""
    _generate_column_line(column_name::AbstractString, column_metadata::AbstractDict{String, Any})

Generates a column definition for the table, based on the column name and the provided metadata for that column.

Column Metadata must be a dictionary, and requires the type to be provided. The total fields are:
1. *type*: SQL type, with or without size, as a string. **This is always required.**
1. *length*: SQL type's length, as a string or integer.
1. *check*: SQL check for the column, as a string, which should return a boolean when run.
1. *not_null*: If included and `true`, the column will be set to NOT NULL.
1. *unique*: If included and `true`, the column will be set to UNIQUE.
1. *primary_key*: If included and `true`, the column will be set to be the PRIMARY KEY
"""
function _generate_column_line(column_name::AbstractString, column_metadata::AbstractDict)
    if !haskey(column_metadata, "type")
        throw(PSQLInterfaceException("All column definitions require a type."))
    end
    type_length = haskey(column_metadata, "length") ? " ($(column_metadata["length"]))" : ""
    check = haskey(column_metadata, "check") ? " CHECK ($(column_metadata["check"]))" : ""
    not_null = get(column_metadata, "not_null", false) ? " NOT NULL" : ""
    unique = get(column_metadata, "unique", false) ? " UNIQUE" : ""
    primary = get(column_metadata, "primary_key", false) ? " PRIMARY KEY" : ""
    return "$(column_name) $(uppercase(column_metadata["type"]))$(type_length)$(unique)$(primary)$(not_null)$(check)"
end


"""
    _delimit_object_names(str::String)

Private method for delimiting object names, such as tables, schemas, and column headers. Required for `camelCase` or any
capitalisation to work correctly. This assumes that your string is splitablle on `.` and will rejoin on this delimiter.
"""
function _delimit_object_names(str::AbstractString)
    return join(map(x -> first(x) == '\"' ? x : '\"'*x*'\"', split(str, ".")), ".")
end